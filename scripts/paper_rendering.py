def number(value):
    # Avoid scientific notation in TeX option limits and make zero exact.
    return f'{value:.10f}'.rstrip('0').rstrip('.') if value else '0'


def axis(options, body):
    return ('% Generated by navigation_planta; do not edit by hand.\n'
            '\\begin{tikzpicture}[baseline=(paperAxis.north)]\n'
            '\\begin{axis}[name=paperAxis,\n' + ',\n'.join(options) + '\n]\n' +
            body + '\\end{axis}\n\\end{tikzpicture}\n')


