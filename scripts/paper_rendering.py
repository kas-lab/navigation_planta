def run_command(arguments, *, cwd=None, timeout=120):
    try:
        result = subprocess.run(arguments, cwd=cwd, capture_output=True, text=True,
                                timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise RuntimeError(f'Could not execute {arguments[0]}: {exc}') from exc
    if result.returncode:
        raise RuntimeError(f'{arguments[0]} failed ({result.returncode}):\n'
                           f'{result.stdout[-6000:]}\n{result.stderr[-2000:]}')
    return result


def preflight():
    tools = ('pdflatex', 'pdftoppm', 'kpsewhich')
    missing = [name for name in tools if not shutil.which(name)]
    if missing:
        raise RuntimeError(f'Missing rendering executables: {", ".join(missing)}. '
                           'Install TeX Live (standalone/PGFPlots/booktabs) and Poppler.')
    packages = ('standalone.cls', 'pgfplots.sty', 'tikz.sty', 'booktabs.sty',
                'multirow.sty', 'caption.sty', 'varwidth.sty', 'preview.sty',
                'tikzlibrarypgfplots.statistics.code.tex',
                'tikzlibrarypgfplots.fillbetween.code.tex', 'libertine.sty')
    for package in packages:
        # kpsewhich returns 1 if absent; make that a clear dependency error.
        try:
            run_command(['kpsewhich', package])
        except RuntimeError as exc:
            raise RuntimeError(f'Missing TeX dependency: {package}') from exc
    versions = {'python': sys.version.split()[0]}
    for tool, flag in [('pdflatex', '--version'), ('pdftoppm', '-v')]:
        result = run_command([tool, flag])
        versions[tool] = (result.stdout or result.stderr).splitlines()[0]
    return versions


