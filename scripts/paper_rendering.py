BOX_STYLES = {
    'time': dict(ylabel='Planning time [s]', min=.3, max=30, ticks=(1, 10)),
    # Keep the exported unit explicit rather than relabelling MiB as MB.
    'peak_memory': dict(ylabel='RSS Peak Memory [MiB]', min=5, max=10000, ticks=(10, 100, 1000, 10000)),
    'remaining_battery': dict(ylabel='Remaining battery', min=10000, max=34000,
                              ticks=(15000, 20000, 25000, 30000)),
    'distance': dict(ylabel='Distance traveled', min=0, max=185, ticks=(0, 50, 100, 150)),
    'move_action': dict(ylabel='Number of actions', min=0, max=17, ticks=(0, 4, 8, 12, 16)),
    'reconfig_action': dict(ylabel='Number of actions', min=0, max=4.5, ticks=(0, 1, 2, 3, 4)),
}


def nice_step(value):
    """Choose a clean 1/2/5 interval, not an arbitrary sampled data coordinate."""
    power = 10 ** math.floor(math.log10(value))
    return next(factor * power for factor in (1, 2, 5, 10) if factor * power >= value)


def sweep_ticks(sid, low, high):
    style = SWEEP_STYLES[sid]
    xmin, xmax = min(style['xmin'], low), max(style['xmax'], high)
    step = style['step'] if xmax <= style['xmax'] else nice_step((xmax - xmin) / 5)
    ticks = [i * step for i in range(math.ceil(xmin / step), math.floor(xmax / step) + 1)]
    if sid == 's1' and xmax not in ticks:
        ticks.append(xmax)
    return xmin, xmax, ticks


def line_plot(sid, datasets, plot_metric='time', latex_prefix=''):
    selected = [d for d in datasets if d['kind'] == 'sweep' and d['sid'] == sid and
                (d['mode'] == 'adaptive' or
                 (plot_metric == 'time' and sid in ('s1', 's4') and d['strategy'] == 'astar'))]
    selected.sort(key=lambda d: (d['mode'] != 'adaptive', d['strategy'] != 'astar'))
    group = selected[0]['group']
    metric = {'time': 'time', 'action': 'action_count', 'memory': 'peak_memory'}[plot_metric]
    mean_column = f'mean_{metric}'
    x_values = [row[group] for row in selected[0]['processed']]
    upper = max(row[f'{mean_column}_plus_std'] for d in selected for row in d['processed'])
    style = SWEEP_STYLES[sid]
    xmin, xmax, ticks = sweep_ticks(sid, min(x_values), max(x_values))
    original_max = style.get(f'{plot_metric}_max', 0)
    ymax = original_max if upper <= original_max and original_max else max(upper * 1.1, 1e-6)
    ylabel = {'time': 'Planning Time [seconds]', 'action': 'Plan Length [no. of actions]',
              'memory': 'RSS Peak Memory [MiB]'}[plot_metric]
    options = ['width=\\textwidth', 'height=0.75\\textwidth',
               f'xlabel={{{style["xlabel"]}}}',
               f'ylabel={{{ylabel}}}',
               f'xmin={number(xmin)}', f'xmax={number(xmax)}',
               'ymin=0', f'ymax={number(ymax)}',
               'xtick={' + ','.join(map(number, ticks)) + '}', 'grid=major',
               'legend pos=north west',
               'legend style={font=\\footnotesize,nodes={scale=0.8,transform shape}}',
               'legend image post style={scale=0.5}']
    body = ''
    for index, d in enumerate(selected):
        color = '\\greenColor' if d['strategy'] == 'astar' else '\\blueColor'
        label = 'A* mean' if d['strategy'] == 'astar' else 'EG mean'
        if d['mode'] == 'no-adaptation':
            color, label = '\\orangeColor', 'No adap. mean'
        path = f'{latex_prefix + "/" if latex_prefix else ""}data/{d["stem"]}_processed.csv'
        for bound, column in [('upper', f'{mean_column}_plus_std'), ('lower', f'{mean_column}_minus_std')]:
            body += (f'\\addplot[name path={bound}{index},draw=none,forget plot] '
                     f'table[x={group},y={column},col sep=comma] {{{path}}};\n')
        body += (f'\\addplot[fill={color}!20,fill opacity=0.3,draw=none,forget plot] '
                 f'fill between[of=upper{index} and lower{index}];\n'
                 f'\\addplot[thick,color={color}] table[x={group},y={mean_column},col sep=comma] '
                 f'{{{path}}};\n\\addlegendentry{{{label}}}\n')
    return axis(options, body)


def box_plot(method, metric, suffix, ylabel, camara, latex_prefix=''):
    imports, body = '', ''
    stats_list = [camara[m]['metrics'][metric] for m in ('prism', method)]
    # Include full extrema, not only whiskers; every sampled tail fits.
    low, high = min(s['min'] for s in stats_list), max(s['max'] for s in stats_list)
    logarithmic = metric in ('time', 'peak_memory') and low > 0
    style = BOX_STYLES[metric]
    options = ['width=\\textwidth', 'height=0.75\\textwidth', 'boxplot/draw direction=y',
               'xmin=0', 'xmax=3', 'xtick={1,2}',
               'xticklabels={\\CamaraApproach,' + ('\\paperEagerLabel' if method == 'eager' else '\\paperAstarLabel') + '}',
               f'ylabel={{{style["ylabel"]}}}', 'ymajorgrids=true']
    # Keep the original view unless observations require more room. Never clip tails.
    if logarithmic:
        ymin = style['min'] if low >= style['min'] else low / 1.3
        ymax = style['max'] if high <= style['max'] else high * 1.3
        options.append('ymode=log')
    else:
        span = max(high - low, high * .1, 1)
        ymin = style['min'] if low >= style['min'] else max(0, low - span * .12)
        ymax = style['max'] if high <= style['max'] else high + span * .15
    ticks = list(style['ticks'])
    if ymax > style['max'] or ymin < style['min']:
        if logarithmic:
            ticks = [10 ** n for n in range(math.ceil(math.log10(ymin)),
                                            math.floor(math.log10(ymax)) + 1)]
        else:
            step = nice_step((ymax - ymin) / 4)
            ticks = [i * step for i in range(math.ceil(ymin / step), math.floor(ymax / step) + 1)]
    options += [f'ymin={number(ymin)}', f'ymax={number(ymax)}',
                'ytick={' + ','.join(map(number, ticks)) + '}']
    if metric == 'time':
        options += ['extra y ticks={0.5,30}', 'extra y tick labels={0.5,30}']
    if metric == 'remaining_battery':
        options.append('scaled y ticks=false')
    for position, m in enumerate(('prism', method), 1):
        filename_metric = 'comparable_move' if metric == 'move_action' and m != 'prism' else metric
        filename = f'{latex_prefix + "/" if latex_prefix else ""}data/{METHOD_STEMS[m]}_{filename_metric}'
        prefix = METHOD_PREFIXES[m] + suffix
        imports += f'\\input{{{filename}_boxstats.tex}}%\n'
        color = '\\blueColor' if m == 'prism' else '\\greenColor'
        keys = [('lower whisker', 'LW'), ('lower quartile', 'LQ'), ('median', 'MED'),
                ('upper quartile', 'UQ'), ('upper whisker', 'UW')]
        prepared = ','.join(f'{key}=\\{prefix}{macro}' for key, macro in keys)
        body += (f'\\addplot+[boxplot prepared={{{prepared},draw position={position},box extend=0.2}},'
                 f'draw={color},fill={color}!30,line width=0.75pt,mark=o,'
                 f'mark options={{fill={color},draw={color},opacity=0.2,line width=0.5pt}}] '
                 f'table[y=y,col sep=comma] {{{filename}_outliers.csv}}\n'
                 f'node[left,text={color}] at '
                 f'(boxplot box cs: \\{prefix}MED,0) '
                 f'{{\\pgfmathprintnumber{{\\{prefix}MED}}}};\n')
    return imports + axis(options, body)


EXPERIMENT_LABELS = dict(zip(('s1', 's2', 's3', 's4', 's5'),
                             (r'\Sone', r'\Stwo', r'\Sthree', r'\Sfour', r'\Sfive')))


def table_fragment(caption, label, columns, header, rows, *, width=r'\linewidth'):
    return (r'\begin{table}[tb]' + '\n\\centering\n'
            f'\\caption{{{caption}}}\\label{{{label}}}\n'
            f'\\resizebox{{{width}}}{{!}}{{%\n' + f'\\begin{{tabular}}{{{columns}}}\n\\toprule\n' +
            header + '\n\\midrule\n' + '\n'.join(' & '.join(row) + r' \\' for row in rows) +
            '\n\\bottomrule\n\\end{tabular}%\n}\n\\end{table}\n')


def generate_tables(root, datasets, endpoints, camara):
    endpoint_rows, table_rows = [], []
    for sid, _, group, _, _ in SWEEPS:
        row = {'experiment': sid.upper()}
        display = [EXPERIMENT_LABELS[sid]]
        for strategy in ('astar', 'eager'):
            endpoint = next(d for d in endpoints if d['experiment'] == sid and
                            d['strategy'] == strategy and d['mode'] == 'adaptive')
            row['x'] = endpoint[group]
            for metric in ('time', 'action_count'):
                for stat in ('mean', 'std'):
                    value = endpoint[f'{stat}_{metric}']
                    row[f'{strategy}_{stat}_{metric}'] = value
                    display.append(f'{value:.2f}')
        endpoint_rows.append(row)
        table_rows.append(display)
    write_csv(root / 'tables/scalability_summary.csv', endpoint_rows)
    parameter_labels = ('nodes', 'architectural configurations', 'corridor types',
                        'mission-level actions', 'nodes')
    caption = ('Scalability experiment results at the maximum tested parameter value for each experiment (' +
               '; '.join(f'{EXPERIMENT_LABELS[r["experiment"].lower()]}: {r["x"]:g} {parameter}'
                         for r, parameter in zip(endpoint_rows, parameter_labels)) +
               ').')
    header = (r'\multirow{3}{*}{\textbf{Exp.}} & \multicolumn{4}{c}{\textbf{A*}}'
              r' & \multicolumn{4}{c}{\textbf{Eager greedy}} \\' + '\n' +
              r'\cmidrule(lr){2-5}\cmidrule(lr){6-9}' + '\n' +
              r' & \multicolumn{2}{c}{\textbf{Planning time (s)}} & \multicolumn{2}{c}{\textbf{Plan length}}'
              r' & \multicolumn{2}{c}{\textbf{Planning time (s)}} & \multicolumn{2}{c}{\textbf{Plan length}} \\' + '\n' +
              r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}\cmidrule(lr){8-9}' + '\n' +
              ' & ' + ' & '.join([r'\textbf{Mean}', r'\textbf{Std.}'] * 4) + r' \\')
    (root / 'tables/scalability_summary.tex').write_text(
        table_fragment(caption, 'tab:scalability_summary', 'lcccccccc', header, table_rows,
                       width=r'.75\textwidth'), encoding='utf-8')
    rows, display_rows = [], []
    for method in ('prism', 'eager', 'astar'):
        row = {'method': method, 'n': len(camara[method]['rows'])}
        display = [METHOD_LABELS[method].replace('Cámara', r"C\'amara"), str(row['n'])]
        for metric, _, _, _ in CAMARA_METRICS:
            value = camara[method]['metrics'][metric]['median']
            row[f'median_{metric}'] = value
            display.append(f'{value:.2f}')
        rows.append(row)
        display_rows.append(display)
    write_csv(root / 'tables/camara_summary.csv', rows)
    header = r'Method & $n$ & Time (s) & RSS (MiB) & Battery & Distance (m) & Moves & Reconfigs. \\'
    (root / 'tables/camara_summary.tex').write_text(table_fragment(
        'Navigation comparison medians. PDDL moves are counted on original map edges.',
        'tab:camara_export_summary', 'lrrrrrrr', header, display_rows), encoding='utf-8')


def wrapper(fragment, latex_prefix=''):
    prefix = latex_prefix + '/' if latex_prefix else ''
    fragment_path = prefix + fragment.as_posix()
    if fragment.parts[0] == 'tables':
        return (r'\documentclass{article}' + '\n' +
                r'\usepackage[T1]{fontenc}' + '\n' +
                r'\usepackage{booktabs,multirow,caption,graphicx}' + '\n' +
                r'\usepackage[active,tightpage,floats]{preview}' + '\n' +
                '\n'.join(f'\\providecommand{{{macro}}}{{\\emph{{{sid.upper()}}}}}'
                          for sid, macro in EXPERIMENT_LABELS.items()) + '\n' +
                r'\begin{document}' + '\n' +
                f'\\input{{{fragment_path}}}\n\\end{{document}}\n')
    return (r'\documentclass[varwidth=18cm,border=5pt]{standalone}' + '\n' +
            r'\usepackage[T1]{fontenc}' + '\n' +
            r'\usepackage[tt=false]{libertine}' + '\n' +
            r'\usepackage{tikz,pgfplots,booktabs,multirow,caption,graphicx}' + '\n' +
            f'\\input{{{prefix}plots/paper_support.tex}}' + '\n' +
            r'\begin{document}' + '\n' +
            f'\\input{{{fragment_path}}}\n\\end{{document}}\n')


def generate_sources(root, datasets, endpoints, camara, *, latex_prefix='', previews=True):
    (root / 'plots/paper_support.tex').write_text(SUPPORT, encoding='utf-8')
    fragments = []
    for sid, _, _, _, _ in SWEEPS:
        for metric in SWEEP_PLOT_METRICS:
            name = f'{sid}_{metric}_plot.tex'
            path = Path('plots') / name
            (root / path).write_text(line_plot(sid, datasets, metric, latex_prefix), encoding='utf-8')
            fragments.append(path)
    for method in ('eager', 'astar'):
        for metric, suffix, plot_suffix, ylabel in CAMARA_METRICS:
            path = Path('plots') / f'camara_map_{plot_suffix}{"_astar" if method == "astar" else ""}.tex'
            (root / path).write_text(box_plot(method, metric, suffix, ylabel, camara, latex_prefix), encoding='utf-8')
            fragments.append(path)
    generate_tables(root, datasets, endpoints, camara)
    fragments += [Path('tables/scalability_summary.tex'), Path('tables/camara_summary.tex')]
    if previews:
        for fragment in fragments:
            (root / 'standalone' / fragment.name).write_text(wrapper(fragment, latex_prefix), encoding='utf-8')
    return fragments


def render_previews(root, fragments, *, latex_prefix=''):
    """Compile each fragment once, then rasterize its PDF; no second plot engine."""
    with tempfile.TemporaryDirectory(prefix='paper-tex-') as temporary:
        build = Path(temporary)
        working_directory = root
        if latex_prefix:
            # Emulate the LaTeX project root while rendering the exact sources.
            working_directory = build / 'project'
            target = working_directory / latex_prefix
            target.parent.mkdir(parents=True)
            target.symlink_to(root.resolve(), target_is_directory=True)
        prefix = latex_prefix + '/' if latex_prefix else ''
        for fragment in fragments:
            print(f'Rendering {fragment}', flush=True)
            run_command(['pdflatex', '-halt-on-error', '-interaction=nonstopmode',
                         '-no-shell-escape', f'-output-directory={build}',
                         f'{prefix}standalone/{fragment.name}'], cwd=working_directory)
            pdf = build / f'{fragment.stem}.pdf'
            if not pdf.is_file() or not pdf.stat().st_size:
                raise RuntimeError(f'No PDF produced for {fragment}')
            destination = root / fragment.with_suffix('.pdf')
            shutil.copyfile(pdf, destination)
            run_command(['pdftoppm', '-singlefile', '-png', '-r', '300', str(destination),
                         str(destination.with_suffix(''))], cwd=root)
            png = destination.with_suffix('.png')
            if not png.is_file() or not png.stat().st_size:
                raise RuntimeError(f'No PNG produced for {fragment}')
